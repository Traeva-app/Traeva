#!/usr/bin/env python3
"""Writes the third-party notices that ship inside Traeva.app (#37).

    python3 scripts/third_party_notices.py          # write the file
    python3 scripts/third_party_notices.py --check  # fail if it is stale

The notices cover what is compiled into the app: the Rust crates that
`traeva-app` uses at run time on this platform (`cargo tree -e normal`), and
the npm packages the window's code ships with (package-lock.json, not dev). For each
one: its name, version and license as published, and the license files its
published package contains, word for word. Identical texts are printed once,
with every package that ships them. The PDF reader's compiled-in data (fonts,
CMaps, colour profiles) is covered by docs/third-party-notices.md, which is
included at the end.

Offline: cargo reads the crates already downloaded (`--offline`); the npm
license files come from node_modules. No local path is written into the output.
"""

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src-tauri" / "resources" / "THIRD-PARTY-NOTICES.txt"
PDF_NOTICES = ROOT / "docs" / "third-party-notices.md"
LICENSE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "NOTICE", "UNLICENSE")


def run(*args: str) -> str:
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def license_files(folder: Path) -> list[tuple[str, str]]:
    """The license files at the top of a published package, by name."""
    found = []
    for path in sorted(folder.iterdir()):
        if path.is_file() and path.name.upper().startswith(LICENSE_PREFIXES):
            text = path.read_bytes().decode("utf-8", errors="replace")
            found.append((path.name, text.replace("\r\n", "\n").strip() + "\n"))
    return found


def rust_packages() -> list[dict]:
    names = set()
    for line in run(
        "cargo", "tree", "-p", "traeva-app", "-e", "normal", "--prefix", "none",
        "--format", "{p}", "--offline",
    ).splitlines():
        line = line.split(" (")[0].strip()
        if line and not line.startswith("traeva"):
            names.add(line)
    metadata = json.loads(run("cargo", "metadata", "--format-version", "1", "--offline"))
    packages = {}
    for package in metadata["packages"]:
        key = f"{package['name']} v{package['version']}"
        if key in names and key not in packages:
            files = license_files(Path(package["manifest_path"]).parent)
            packages[key] = {
                "kind": "Rust crate",
                "name": package["name"],
                "version": package["version"],
                "license": package.get("license") or "(see its license file)",
                "repository": package.get("repository") or "",
                "files": files,
            }
    missing = names - packages.keys()
    if missing:
        sys.exit(f"cargo metadata lacks: {sorted(missing)}")
    return [packages[key] for key in sorted(packages)]


def npm_packages() -> list[dict]:
    """The packages package-lock.json installs for production (not dev)."""
    lock = json.loads((ROOT / "package-lock.json").read_text())
    found = {}
    for path, info in lock["packages"].items():
        if not path.startswith("node_modules/") or info.get("dev"):
            continue
        name = path.split("node_modules/")[-1]
        key = f"{name}@{info['version']}"
        folder = ROOT / path
        manifest = json.loads((folder / "package.json").read_text())
        repository = manifest.get("repository") or ""
        if isinstance(repository, dict):
            repository = repository.get("url", "")
        found[key] = {
            "kind": "npm package",
            "name": name,
            "version": info["version"],
            "license": info.get("license") or manifest.get("license") or "(see its license file)",
            "repository": repository,
            "files": license_files(folder),
        }
    return [found[key] for key in sorted(found)]


def render(packages: list[dict]) -> str:
    out = [
        "THIRD-PARTY NOTICES FOR TRAEVA",
        "",
        "Traeva includes the open-source software listed below. Each package is",
        "used under the license (or one of the licenses) it is published with.",
        "The license texts follow, word for word as each published package ships",
        "them; packages that ship the same text are listed together above it.",
        "Generated by scripts/third_party_notices.py; do not edit by hand.",
        "",
        f"Rust crates: {sum(p['kind'] == 'Rust crate' for p in packages)}. "
        f"npm packages: {sum(p['kind'] == 'npm package' for p in packages)}.",
        "SQLite, compiled in through libsqlite3-sys, is in the public domain.",
        "",
        "=" * 72,
        "PACKAGES",
        "=" * 72,
        "",
    ]
    for p in packages:
        repository = f"  {p['repository']}" if p["repository"] else ""
        out.append(f"{p['name']} {p['version']} ({p['kind']}): {p['license']}{repository}")
    groups: dict[str, dict] = {}
    without = []
    for p in packages:
        if not p["files"]:
            without.append(p)
        for file_name, text in p["files"]:
            digest = hashlib.sha256(text.encode()).hexdigest()
            group = groups.setdefault(digest, {"text": text, "users": []})
            group["users"].append(f"{p['name']} {p['version']} ({file_name})")
    out += ["", "=" * 72, "LICENSE TEXTS", "=" * 72]
    for group in sorted(groups.values(), key=lambda g: g["users"][0]):
        out += ["", "-" * 72, "Shipped by:"]
        out += [f"  {user}" for user in group["users"]]
        out += ["-" * 72, "", group["text"].rstrip()]
    if without:
        out += [
            "", "=" * 72,
            "PACKAGES THAT SHIP NO LICENSE FILE",
            "=" * 72, "",
            "These packages declare their license in their manifest only; its",
            "standard text applies. The MIT, Apache-2.0, Zlib and MPL-2.0 texts",
            "are above, shipped by other packages; the BSD-3-Clause notice of the",
            "Brotli family (alloc-stdlib) is in the PDF reader section below.",
            "",
        ]
        out += [f"  {p['name']} {p['version']}: {p['license']}" for p in without]
    out += [
        "", "=" * 72,
        "DATA COMPILED INTO THE PDF READER",
        "=" * 72, "",
        PDF_NOTICES.read_text().strip(),
        "",
    ]
    return "\n".join(out)


def main() -> None:
    text = render(rust_packages() + npm_packages())
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            sys.exit(f"{OUTPUT.relative_to(ROOT)} is stale: run scripts/third_party_notices.py")
        print("up to date")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(text.encode())} bytes)")


if __name__ == "__main__":
    main()
